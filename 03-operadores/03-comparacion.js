let a = 10;
console.log("Valor de a: " + a);
console.log("Comparación a == 10: " + (a == 10));   // Igualdad
console.log("Comparación a === 10: " + (a === "10"));  // Igualdad estricta
console.log("Comparación a != 5: " + (a != 10));   // Desigualdad
console.log("Comparación a !== 5: " + (a !== "10"));  // Desigualdad estricta

console.log("Comparación a > 5: " + (a > 5));    // Mayor que
console.log("Comparación a < 15: " + (a < 5));   // Menor que
console.log("Comparación a >= 10: " + (a >= 5));  // Mayor o igual que
console.log("Comparación a <= 20: " + (a <= 5));  // Menor o igual que
